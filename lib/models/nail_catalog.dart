  NailCategory category,
  String id,
  String name,
  int rgb,
  NailPattern pattern, {
  required int accent,
  double coverage = .98,
  double patternScale = 1.0,
  double variant = 0.0,
  double finishGloss = 1.0,
}) => NailStyle(
  id,
  name,
  '${category.label} · ${pattern.label}',
  Color(0xFF000000 | rgb),
  pattern,
  accent: Color(0xFF000000 | accent),
  category: category,
  coverage: coverage,
  patternScale: patternScale,
  variant: variant,
  finishGloss: finishGloss,
);
